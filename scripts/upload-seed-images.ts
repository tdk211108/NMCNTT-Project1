import { createHash } from 'node:crypto';
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createClient } from '@supabase/supabase-js';
import { eq } from 'drizzle-orm';
import { createDbConnection } from '../src/server/db/client';
import { products } from '../src/server/db/schema';
import { buildSeedImageUrl } from '../src/server/db/seed/seed-catalog';
import { resolveStorageConfig } from '../src/server/storage/supabase-storage';
import { SEED_IMAGE_PREFIX } from '../src/shared/constants';
import { loadProjectEnv } from './lib/load-env';

const CONTENT_TYPES: Record<string, string> = {
  '.webp': 'image/webp',
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
};

const CONCURRENCY = 8;
const IMAGE_HASH_HEX_LEN = 8;
const VERSIONS_FILE_PATH = path.join(
  process.cwd(),
  'src',
  'server',
  'db',
  'seed',
  'data',
  'image-versions.ts',
);

function renderImageVersionsModule(hashes: Record<string, string>): string {
  const entries = Object.keys(hashes)
    .sort()
    .map((fileName) => `  '${fileName}': '${hashes[fileName]}',`)
    .join('\n');

  return [
    "import 'server-only';",
    '',
    '// Generated by scripts/upload-seed-images.ts (first 8 hex chars of SHA-256 per seed image).',
    'export const SEED_IMAGE_HASHES: Record<string, string> = {',
    entries,
    '};',
    '',
  ].join('\n');
}

async function syncSeedProductUrls(
  hashes: Record<string, string>,
  storage: { supabaseUrl: string; bucket: string },
): Promise<number> {
  const connectionString = (
    process.env.DATABASE_URL_MIGRATIONS ??
    process.env.DATABASE_URL ??
    ''
  ).trim();
  if (!connectionString) {
    return 0;
  }

  const { sql, db } = createDbConnection(connectionString, { max: 1, idleTimeoutSeconds: 10 });
  try {
    return await db.transaction(async (tx) => {
      const seedRows = await tx
        .select({
          id: products.id,
          imageStoragePath: products.imageStoragePath,
          imageUrl: products.imageUrl,
        })
        .from(products)
        .where(eq(products.isSeed, true));

      let updatedCount = 0;
      for (const row of seedRows) {
        if (!row.imageStoragePath?.startsWith(SEED_IMAGE_PREFIX)) {
          continue;
        }
        const fileName = row.imageStoragePath.slice(SEED_IMAGE_PREFIX.length);
        const hash = hashes[fileName];
        if (!hash) {
          continue;
        }
        const nextUrl = buildSeedImageUrl(fileName, storage, hash);
        if (row.imageUrl === nextUrl) {
          continue;
        }
        await tx
          .update(products)
          .set({ imageUrl: nextUrl, updatedAt: new Date() })
          .where(eq(products.id, row.id));
        updatedCount += 1;
      }
      return updatedCount;
    });
  } finally {
    await sql.end({ timeout: 5 });
  }
}

async function main(): Promise<void> {
  loadProjectEnv();

  const { supabaseUrl, secretKey, bucket } = resolveStorageConfig();

  const supabase = createClient(supabaseUrl, secretKey, {
    auth: { persistSession: false, autoRefreshToken: false },
  });

  const seedDir = path.join(process.cwd(), 'data', 'seed', 'images');
  const entries = (await readdir(seedDir, { withFileTypes: true }))
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .sort();

  if (entries.length === 0) {
    throw new Error('No files found inside data/seed/images/.');
  }

  const hashes: Record<string, string> = {};
  let uploaded = 0;

  for (let i = 0; i < entries.length; i += CONCURRENCY) {
    const batch = entries.slice(i, i + CONCURRENCY);
    await Promise.all(
      batch.map(async (fileName) => {
        const ext = path.extname(fileName).toLowerCase();
        const contentType = CONTENT_TYPES[ext];
        if (!contentType) {
          throw new Error(`Unsupported image extension for ${fileName}`);
        }

        const fileBuffer = await readFile(path.join(seedDir, fileName));
        hashes[fileName] = createHash('sha256')
          .update(fileBuffer)
          .digest('hex')
          .slice(0, IMAGE_HASH_HEX_LEN);

        const objectPath = `${SEED_IMAGE_PREFIX}${fileName}`;
        const { error } = await supabase.storage.from(bucket).upload(objectPath, fileBuffer, {
          contentType,
          cacheControl: '31536000',
          upsert: true,
        });

        if (error) {
          throw new Error(`Failed to upload ${objectPath}: ${error.message}`);
        }
        uploaded += 1;
      }),
    );
  }

  await writeFile(VERSIONS_FILE_PATH, renderImageVersionsModule(hashes), 'utf8');
  const dbUpdated = await syncSeedProductUrls(hashes, { supabaseUrl, bucket });

  console.log(
    `Uploaded ${uploaded} seed images to bucket "${bucket}" under "${SEED_IMAGE_PREFIX}", wrote image-versions.ts, and updated ${dbUpdated} DB product URLs.`,
  );
}

main().catch((err) => {
  console.error('Seed image upload failed:', err);
  process.exit(1);
});
